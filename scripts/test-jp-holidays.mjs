let ng = 0;
for (const [y, table] of Object.entries(expected)) {
  // その年の全日を回して、祝日である日・ない日の両方を突き合わせる
  for (let d = new Date(Number(y), 0, 1); d.getFullYear() === Number(y); d.setDate(d.getDate() + 1)) {
    const md = `${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
    const got = f(`${y}-${md}`);
    const want = table[md] ?? null;
    if (got !== want) { ng++; console.error(`❌ ${y}-${md}: 期待=${want} 実際=${got}`); }
  }
}
if (f("2026-9-22") !== null || f("abc") !== null) { ng++; console.error("❌ 形式が違う文字列は null を返すこと"); }
if (ng > 0) { console.error(`\n祝日計算が ${ng} 件ずれています`); process.exit(1); }
