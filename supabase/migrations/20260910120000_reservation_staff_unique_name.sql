-- スタッフ名の重複を DB で禁止する（同じ院に同じ名前のスタッフを2件作れない）。
--
-- 背景（2026-09-10 ボール接骨院の事故）:
--   8/27 に設定画面から「ボール」がもう1件追加され、ボールが2人になった。
--   受付が新規予約で2件目の「ボール」を選んだため、予約サイト側
--   （メニューの担当＝1件目のボール）からはその予約が見えず、
--   埋まっている 17:30 が「予約可」と表示された。
--   アプリ側の重複チェック（saveStaff）だけでなく DB でも二重に止める。
--
-- 比較は 前後の空白を除いた小文字 で行う（「ボール」「 ボール 」を同一視）。
create unique index if not exists uq_reservation_staff_clinic_name
  on public.reservation_staff (clinic_id, lower(btrim(name)));
